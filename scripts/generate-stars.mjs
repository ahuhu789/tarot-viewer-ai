// Generates src/app/stars.generated.css: static box-shadow star fields for the
// pure-CSS night sky (no canvas, no JS animation). Deterministic (seeded), so the
// output only changes when this script changes. Run: node scripts/generate-stars.mjs
import fs from 'node:fs';

const FIELD = 2000; // px; the field is scaled down on small screens (see globals.css)
let seed = 20261021;
const rand = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (list) => {
  let r = rand() * list.reduce((a, [, w]) => a + w, 0);
  for (const [v, w] of list) if ((r -= w) <= 0) return v;
  return list[0][0];
};
// Mostly white, some lilac / pale blue, a rare warm star.
const COLORS = [['#ffffff', 60], ['#e3d9ff', 22], ['#cddcff', 12], ['#ffe7b8', 6]];
const alpha = (min, max) => Math.round((min + rand() * (max - min)) * 255).toString(16).padStart(2, '0');

function field(count, { aMin, aMax, glow = 0 }) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const x = Math.round(rand() * FIELD);
    const y = Math.round(rand() * FIELD);
    const c = pick(COLORS);
    out.push(`${x}px ${y}px ${c}${alpha(aMin, aMax)}`);
    if (glow) out.push(`${x}px ${y}px ${glow}px ${c}66`);
  }
  return out.join(',');
}

// Milky-way band: stars clustered (gaussian) around a diagonal line across the field.
const gauss = () => (rand() + rand() + rand() + rand() - 2) / 2; // ~N(0, 0.4)
function band(count, { aMin, aMax, width }) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const t = rand();
    const off = gauss() * width;
    // line from (0, 900) to (2000, -210): lower-left to upper-right; normal ~ (0.49, 0.87)
    const x = Math.round(t * FIELD + off * 0.49);
    const y = Math.round(900 - t * 1110 + off * 0.87);
    if (x < 0 || y < 0 || x > FIELD || y > FIELD) continue;
    out.push(`${x}px ${y}px ${pick(COLORS)}${alpha(aMin, aMax)}`);
  }
  return out.join(',');
}

const groups = {
  m1: band(400, { aMin: 0.25, aMax: 0.7, width: 260 }),
  m2: band(260, { aMin: 0.3, aMax: 0.8, width: 180 }),
  // tiny 1px stars in four twinkle groups
  t1: field(240, { aMin: 0.55, aMax: 1 }),
  t2: field(240, { aMin: 0.55, aMax: 1 }),
  t3: field(240, { aMin: 0.55, aMax: 1 }),
  t4: field(240, { aMin: 0.55, aMax: 1 }),
  // small 2px stars
  s1: field(110, { aMin: 0.65, aMax: 1 }),
  s2: field(110, { aMin: 0.65, aMax: 1 }),
  s3: field(110, { aMin: 0.65, aMax: 1 }),
  // a few bright 3px stars with a soft halo
  b1: field(20, { aMin: 0.9, aMax: 1, glow: 6 }),
  b2: field(20, { aMin: 0.9, aMax: 1, glow: 6 }),
};

let css = `/* AUTO-GENERATED by scripts/generate-stars.mjs — do not edit by hand. */\n`;
for (const [k, v] of Object.entries(groups)) css += `.stars--${k}{box-shadow:${v}}\n`;
fs.writeFileSync(new URL('../src/app/stars.generated.css', import.meta.url), css);
console.log('stars.generated.css', (css.length / 1024).toFixed(1), 'KB');
